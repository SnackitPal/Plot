def get_slate_by_day(day_number: int) -> Optional[Dict[str, Any]]:
    """Retrieve full slate configuration for a specific day (1-30)."""
    for slate in SLATES_30D:
        if slate["day_number"] == day_number:
            return slate
    return None


def get_all_slates_metadata(user_completed_days: Optional[List[int]] = None) -> List[Dict[str, Any]]:
    """Return lightweight summary catalog of all 30 slates for calendar ribbon."""
    completed_set = set(user_completed_days or [])
    metadata = []
    for slate in SLATES_30D:
        metadata.append({
            "slate_id": slate["slate_id"],
            "day_number": slate["day_number"],
            "title": slate["title"],
            "release_date": slate["release_date"],
            "domain_tags": slate["domain_tags"],
            "question_count": len(slate["questions"]),
            "is_completed": slate["day_number"] in completed_set,
        })
    return metadata
